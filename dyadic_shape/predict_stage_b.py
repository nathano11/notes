"""Write PREDICTIONS_STAGE_B.md from the analytic side only (no ideal classes).

For each field: (C0, C1) from the Stickelberger row at level 14, the module
M = O/omega_2 O = A(k_2)/<[p_2]> as an abelian group, and the set of (a, b)
modulo the exponent of M with  gamma^2 + a gamma + b = 0  on a Lambda-generator.
"""
import shape_engine as E
from cm_classgroup import hnf

FIELDS = [((3, 23), "project field"), ((11, 263), "project field"),
          ((227, 23), "out of sample, shape I"), ((739, 7), "out of sample, shape IIa"),
          ((11, 503), "out of sample, shape IIb")]
PREC = 13


def layer2(C0, C1):
    Mod = 1 << PREC
    X = [[1, -C0], [1, 1 - C1]]                      # gamma on the basis 1, T (columns)

    def mm(A, B):
        return [[sum(A[i][k] * B[k][j] for k in range(2)) % Mod for j in range(2)] for i in range(2)]
    X2 = mm(X, X)
    X4 = mm(X2, X2)
    W = [[(X4[i][j] - (i == j)) % Mod for j in range(2)] for i in range(2)]
    rows = [[W[0][0], W[1][0]], [W[0][1], W[1][1]], [Mod, 0], [0, Mod]]
    H = hnf(rows, 2)
    d1, d2 = H[0][0], H[1][1]
    order = d1 * d2
    # invariant factors from the 2x2 HNF
    from math import gcd
    g = gcd(gcd(H[0][0], H[0][1]), H[1][1])
    inv = (g, order // g)

    def member(v):
        v = list(v)
        q = v[0] // H[0][0]
        if v[0] % H[0][0]:
            return False
        v = [v[0] - q * H[0][0], v[1] - q * H[0][1]]
        return v[1] % H[1][1] == 0
    e = inv[1]
    sols = []
    for a in range(e):
        for b in range(e):
            v = ((X2[0][0] + a * X[0][0] + b) % Mod, (X2[1][0] + a * X[1][0]) % Mod)
            if member(v):
                sols.append((a, b))
    return inv, e, sols


def main():
    out = ["# Stage B predictions, fixed before any ideal-class computation",
           "",
           "Generated by `predict_stage_b.py` from the analytic side only. The three",
           "out-of-sample fields are the pairs of smallest qd > 5000 of each shape, as",
           "declared in Stage A. `tau = 2 - C1`, `Delta = 1 - C1 + C0`.",
           ""]
    for (q, d), tag in FIELDS:
        m = q * d
        C0, C1, mod, p0, p2 = E.iwasawa_coefficients(q, d, PREC + 1)
        assert mod == 1 << PREC
        c = E.row(q, d, 2)
        hi2 = int((c[0] - c[2]) ** 2 + (c[1] - c[3]) ** 2)
        x, y = E.v2(p0), E.v2(p2)
        leg = 1 if pow(q, (d - 1) // 2, d) == 1 else -1
        if x == y:
            k1 = [2, 2 ** x, 2 ** x]
        else:
            k1 = [2, 2 ** (min(x, y) - 1), 2 ** (max(x, y) + 1)]
        k1 = sorted(f for f in k1 if f > 1)
        fp = [2, 2, 4] if leg == -1 else [2, 2, 2]
        inv, e, sols = layer2(C0, C1)
        out += [f"## ({q},{d}), m = {m}  [{tag}]", "",
                f"* (q/d) = {leg:+d}; h(-4m) = {2 * p0}, h(-8m) = {2 * p2}; "
                f"(C0, C1) = ({C0}, {C1}) mod 2^{PREC}.",
                f"* h(k_1) = {2 * p0 * p2}, 2-part {2 ** (E.v2(p0 * p2) + 1)}; "
                f"h(F') = {2 * hi2}, 2-part {2 ** (E.v2(hi2) + 1)}; "
                f"h(k_2) = {2 * p0 * p2 * hi2}, 2-part {2 ** (E.v2(p0 * p2 * hi2) + 1)}.",
                f"* S5: A(Q(sqrt2, sqrt(-m))) has invariant factors {k1}; A(F') has {fp}.",
                f"* Layer two: A(k_2)/<[p_2]> = O/omega_2 O has invariant factors {list(inv)}, "
                f"exponent {e}.",
                f"* Marked relation: gamma^2 + a gamma + b = 0 on a Lambda-generator exactly for "
                f"(a, b) mod {e} in a set of {len(sols)} pair(s)"
                + (f": {sols}." if len(sols) <= 8 else f"; it contains (-tau, Delta) = "
                   f"({(C1 - 2) % e}, {(1 - C1 + C0) % e})."),
                ""]
    open("PREDICTIONS_STAGE_B.md", "w", encoding="utf-8").write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
