"""Structure of the 2-class group of the layer-two field k_2 (degree 8), by
exhaustion with explicit ideals and principal-ideal tests.

Stage A, prediction S6: (q/d) = -1  =>  A(k_2) = C_2 + C_4 + C_8.
Stage B: A(k_2) / <[p_2]> has the invariant factors listed there, and [p_2] has
order two, so A(k_2) = C_2 + (those factors).

Usage: python test_layer2_group.py q d [max_primes]
"""
import sys
import time

import shape_engine as E_
from cm_classgroup import invariant_factors, two_group
from predict_stage_b import PREC, layer2
from test_layer2 import build, odd_part


def main():
    q, d = int(sys.argv[1]), int(sys.argv[2])
    max_primes = int(sys.argv[3]) if len(sys.argv) > 3 else 10
    m = q * d
    C0, C1, mod, p0, p2 = E_.iwasawa_coefficients(q, d, PREC + 1)
    c = E_.row(q, d, 2)
    hi2 = int((c[0] - c[2]) ** 2 + (c[1] - c[3]) ** 2)
    h = 2 * p0 * p2 * hi2
    hodd = odd_part(h)
    two = h // hodd
    inv, e, _ = layer2(C0, C1)
    predicted = sorted([2] + list(inv))
    t0 = time.time()
    K, Q2, _ = build(m)
    gens = [K.power(K.ramified_prime(Q2.make_totally_positive([0, 1, 0, 0]), None), hodd)]
    used, p = [], 15
    while len(used) < max_primes and p < 3000:
        p += 2
        if p % 16 not in (1, 15) or any(p % f == 0 for f in range(3, int(p ** 0.5) + 1, 2)):
            continue
        if m % p == 0:
            continue
        P = K.split_prime(p)
        if P is None:
            continue
        gens.append(K.power(P, hodd))
        used.append(p)
    G, orders = two_group(K, gens, target_order=two)
    fac = sorted(invariant_factors(orders))
    # the quotient by the class of the prime above 2
    P2, qorders = gens[0], []
    for x in G:
        o, cur = 1, x
        while not (K.is_principal(cur) or K.is_principal(K.product(cur, P2))):
            cur = K.product(cur, cur)
            o *= 2
        qorders.append(o)
    qfac = sorted(invariant_factors(sorted(qorders)[::2]))
    ok = len(G) == two and fac == predicted and qfac == sorted(inv)
    verdict = "AS PREDICTED" if ok else "DISAGREES"
    print(f"({q},{d}) k_2: analytic h = {h}, 2-part {two}; group generated by [p_2] and "
          f"primes above {used} has order {len(G)}, invariant factors {fac}, predicted {predicted}; "
          f"quotient by <[p_2]> has factors {qfac}, predicted {sorted(inv)}; "
          f"{verdict}; {time.time() - t0:.0f}s", flush=True)


if __name__ == "__main__":
    main()
